    "interior_id" INTEGER NOT NULL,
    "x" SMALLINT NOT NULL,
    "y" SMALLINT NOT NULL,

    CONSTRAINT "interior_blocks_pkey" PRIMARY KEY ("interior_id","x","y")
);

