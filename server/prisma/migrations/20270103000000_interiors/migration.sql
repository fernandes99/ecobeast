-- As salas dos interiores e a sala na peça solta (.specs/interiors/01-interior-data.md).
CREATE TABLE "ecobeasts"."interiors" (
    "id" SERIAL NOT NULL,
    "name" TEXT NOT NULL,
    "width" SMALLINT NOT NULL,
    "height" SMALLINT NOT NULL,
    "door_x" SMALLINT NOT NULL,
    "door_y" SMALLINT NOT NULL,
    "updated_at" TIMESTAMPTZ(3) NOT NULL,

    CONSTRAINT "interiors_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "ecobeasts"."interior_tiles" (
    "interior_id" INTEGER NOT NULL,
    "layer" TEXT NOT NULL,
    "x" SMALLINT NOT NULL,
    "y" SMALLINT NOT NULL,
    "sheet" TEXT NOT NULL,
    "col" SMALLINT NOT NULL,
    "row" SMALLINT NOT NULL,

    CONSTRAINT "interior_tiles_pkey" PRIMARY KEY ("interior_id","layer","x","y")
);

CREATE TABLE "ecobeasts"."interior_objects" (
    "id" SERIAL NOT NULL,
    "interior_id" INTEGER NOT NULL,
    "x" SMALLINT NOT NULL,
    "y" SMALLINT NOT NULL,
    "sheet" TEXT NOT NULL,
    "col" SMALLINT NOT NULL,
    "row" SMALLINT NOT NULL,
    "width" SMALLINT NOT NULL,
    "height" SMALLINT NOT NULL,

    CONSTRAINT "interior_objects_pkey" PRIMARY KEY ("id")
);

